# 4. VIBHAKTI (विभक्ती) — Case marker normalization
# ═══════════════════════════════════════════════════════════════════════════

VIBHAKTI_FIXES: List[Tuple[str, str]] = [
    # Doubled postpositions
    (r'(\S)ला\s+ला\b', r'\1ला'),
    (r'(\S)ने\s+ने\b', r'\1ने'),
    (r'(\S)चा\s+चा\b', r'\1चा'),

    # Wrong postposition spacing — should be attached
    # NOTE: Uses (?:^|\s) instead of \b because Python \b is broken for
    # Devanagari — it fires between base chars and combining marks (halant/matra).
    # The postposition list EXCLUDES single-char postpositions (त, स) that
    # would match first chars of following words.
    (r'(?:(?<=\s)|(?<=^))(त्या|या|माझ्या|तुझ्या|आपल्या|त्यां)\s+(ला|ने|शी|हून|चा|ची|चे|वर|खाली|मध्ये|साठी|बद्दल|विषयी|मुळे|पासून|पर्यंत|बरोबर|सोबत|जवळ|समोर|मागे)(?=\s|$|[।॥,;:!?.\-])',
     r'\1\2'),

    # Spelling standardization
    (r'\bमधे\b', 'मध्ये'),
    (r'\bमधी\b', 'मधली'),
    (r'\bमधुन\b', 'मधून'),
    (r'\bमधल\b', 'मधील'),
]


